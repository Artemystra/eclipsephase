/**
 * Moves the native ApplicationV2 window header controls (button.header-control)
 * into a custom container inside the given parent element.
 * Safe to call on every render — no-op if controls are already present.
 * @param {ApplicationV2} sheet - The sheet instance
 * @param {HTMLElement} parent - The element to append controls into
 */
export function addWindowControls(sheet, parent) {
  if (!parent || parent.querySelector(".ep-window-controls")) return;

  const controls = document.createElement("div");
  controls.classList.add("ep-window-controls");

  // Clone native header controls — originals stay in .window-header (persist across re-renders),
  // clones get data-action attributes so ApplicationV2's root-level event delegation handles clicks.
  const nativeButtons = sheet.element?.querySelectorAll('.window-header button.header-control');
  if (nativeButtons?.length) {
    nativeButtons.forEach(btn => controls.appendChild(btn.cloneNode(true)));
  } else {
    // Fallback: manual close button
    const closeBtn = document.createElement("button");
    closeBtn.type = "button";
    closeBtn.classList.add("ep-close-btn");
    closeBtn.innerHTML = '<i class="fa-solid fa-xmark"></i>';
    closeBtn.addEventListener("click", () => sheet.close());
    controls.appendChild(closeBtn);
  }

  parent.appendChild(controls);
}

/**
 * Binds mouse-drag on the given handle element to move the sheet window,
 * replicating the native window-header drag via sheet.setPosition().
 * Only wired once — subsequent calls are no-ops via a data attribute guard.
 * @param {ApplicationV2} sheet - The sheet instance
 * @param {HTMLElement} handle - The element to use as drag handle
 */
export function addDragSupport(sheet, handle) {
  if (!handle || handle.dataset.epDragBound) return;
  handle.dataset.epDragBound = "1";

  handle.addEventListener("mousedown", (event) => {
    if (event.button !== 0) return;
    if (event.target.closest('[data-action], button, input, select')) return;

    event.preventDefault();

    const pos = sheet.position;
    const startX = event.clientX - pos.left;
    const startY = event.clientY - pos.top;

    function onMove(ev) {
      sheet.setPosition({ left: ev.clientX - startX, top: ev.clientY - startY });
    }

    function onUp() {
      document.removeEventListener("mousemove", onMove);
      document.removeEventListener("mouseup", onUp);
    }

    document.addEventListener("mousemove", onMove);
    document.addEventListener("mouseup", onUp);
  });
}

/**
 * Binds double-click on the given handle element to toggle a custom
 * minimized state on the sheet, replicating the native window-header
 * dblclick-minimize (unusable here because the native header is hidden
 * and native minimize would hide the custom title bar along with the rest
 * of the window content). Visual collapse is handled by the .ep-minimized
 * CSS rules in css/eclipsephase.css.
 * Only wired once — subsequent calls are no-ops via a data attribute guard.
 * @param {ApplicationV2} sheet - The sheet instance
 * @param {HTMLElement} handle - The element to use as double-click target
 */
export function addMinimizeSupport(sheet, handle) {
  if (!handle || handle.dataset.epMinimizeBound) return;
  handle.dataset.epMinimizeBound = "1";

  handle.addEventListener("dblclick", async (event) => {
    if (event.target.closest('[data-action], button, input, select')) return;

    event.preventDefault();

    const element = sheet.element;
    if (!element || sheet._epMinimizeAnimating) return;

    if (element.classList.contains("ep-minimized")) {
      // Restore: remove the class, then wait for the max-width/max-height
      // transition to finish before reapplying the stashed size.
      // setPosition() clamps width/height against getComputedStyle()'s
      // maxWidth/maxHeight, and while the transition is still running those
      // compute to the collapsed values, so calling it synchronously would
      // clamp the frame right back down to the minimized size. Core's own
      // maximize() awaits the transition the same way before repositioning.
      sheet._epMinimizeAnimating = true;
      element.classList.remove("ep-minimized");
      await sheet._awaitTransition(element, 1000);
      sheet._epMinimizeAnimating = false;
      if (sheet._epPriorSize && sheet.rendered) {
        sheet.setPosition({
          width: sheet._epPriorSize.width,
          height: sheet._epPriorSize.height
        });
      }
    } else {
      // Minimize: stash the current size on the long-lived sheet instance
      // (survives re-renders, unlike DOM dataset attributes)
      sheet._epPriorSize = {
        width: sheet.position.width,
        height: sheet.position.height
      };
      element.classList.add("ep-minimized");
    }
  });
}

export async function transferItemBetweenActors({
  sourceActor,
  targetActor,
  item,
  quantity = 1,
  boundToOverride
} = {}) {
  if (!sourceActor || !targetActor || !item) return null;

  const sourceQty = Number(item.system.quantity ?? 1);
  const transferQty = Math.max(1, Number(quantity) || 1);

  const itemData = item.toObject();
  delete itemData._id;

  if (foundry.utils.hasProperty(itemData, "system.quantity")) {
    itemData.system.quantity = Math.min(sourceQty, transferQty);
  }

  // boundTo is only meaningful within the actor it was resolved against - a value carried over
  // verbatim from the source actor would point at a body that doesn't exist on the target.
  if (boundToOverride !== undefined && foundry.utils.hasProperty(itemData, "system.boundTo")) {
    itemData.system.boundTo = boundToOverride;
  }

  const existing = targetActor.items.find(i =>
    i.type === item.type &&
    i.name === item.name
  );

  let createdOrUpdated;
  if (existing && foundry.utils.hasProperty(existing.system, "quantity")) {
    const currentQty = Number(existing.system.quantity ?? 0);
    await existing.update({
      "system.quantity": currentQty + Math.min(sourceQty, transferQty)
    });
    createdOrUpdated = existing;
  } else {
    [createdOrUpdated] = await targetActor.createEmbeddedDocuments("Item", [itemData]);
  }

  if (sourceQty <= transferQty) {
    await sourceActor.deleteEmbeddedDocuments("Item", [item.id]);
  } else {
    await item.update({
      "system.quantity": sourceQty - transferQty
    });
  }

  return createdOrUpdated;
}