/**
 * Toggles the active state of an item and its effects.
 * This is the main function to handle automatic active effect
 * toggle on morph switch.
 * @param {Object} html - The html object of the actor sheet
 * @param {Object} actor - The actor object
 */
export function embeddedItemToggle(html, actor) {
  html.querySelectorAll(".equipped.checkBox").forEach(element => {
    element.addEventListener("click", async ev => {
      let updateData = {};
      let toggle;
      let path;
      const data = ev.currentTarget.dataset;
      const itemId = data.itemId;
      const item = actor.items.get(itemId);
      if (!item) return;

      //checks whether a radiomenu and toggles everything that's not the currentTarget off
      if (data.grouppath) {
        path = foundry.utils.getProperty(item, data.grouppath);
        for (let entry in path) {
          if (entry != data.currenttargetkey) {
            let updatePath = data.grouppath + "." + entry + ".active";
            updateData[updatePath] = false;
          }
          else {
            let updatePath = data.grouppath + "." + entry + ".active";
            updateData[updatePath] = true;
          }
        }
        await item.update(updateData);
        return;
      }

      //toggles the checkbox on/off
      if (!data.path) {
        toggle = !item.system.active;
        path = "system.active";
      }
      else {
        path = data.path;
        toggle = !foundry.utils.getProperty(item, path);
      }

      updateData[path] = toggle;
      await item.update(updateData);
    });
  });
}

/**
 * Powers any ".multiselect-widget" (see templates/actor/partials/multiselect-pills.html) - a
 * reusable multi-select that stores its values as an array on the widget's data-path.
 * Add: type into .multiselect-input and press Enter (free text allowed), or pick a suggestion
 * from the custom .multiselect-dropdown (filtered while typing, arrow keys to highlight).
 * Remove: click a .multiselect-pill-remove.
 * @param {Object} html - The HTML object to which the event listeners are added
 * @param {Object} actor - The actor object whose data-path array fields are being edited
 */
export function multiSelectPills(html, actor) {
  html.querySelectorAll(".multiselect-widget").forEach(widget => {
    const path = widget.dataset.path;
    if (!path) return;

    const input = widget.querySelector(".multiselect-input");
    const dropdown = widget.querySelector(".multiselect-dropdown");

    // shared by the Enter-key path and the option-click path
    const addValue = async rawValue => {
      const value = String(rawValue ?? "").trim();
      if (!value) return;

      const values = foundry.utils.duplicate(foundry.utils.getProperty(actor, path) ?? []);
      const alreadyAdded = values.some(existing => String(existing).toLowerCase() === value.toLowerCase());
      if (alreadyAdded) {
        input.value = "";
        return;
      }

      values.push(value);
      await actor.update({ [path]: values });
      input.value = "";
    };

    const hideDropdown = () => {
      if (!dropdown) return;
      dropdown.classList.add("noShow");
      dropdown.classList.remove("showFlex");
      clearHighlight();
    };

    const clearHighlight = () => {
      if (!dropdown) return;
      dropdown.querySelectorAll(".multiselect-option-active").forEach(option => option.classList.remove("multiselect-option-active"));
    };

    const visibleOptions = () => dropdown ? [...dropdown.querySelectorAll(".multiselect-option:not(.noShow)")] : [];

    // Show options whose text contains the typed value (all of them while the input is empty,
    // so focusing the field doubles as browsing the full list); hide the box if nothing matches.
    const filterDropdown = () => {
      if (!dropdown) return;
      clearHighlight();
      const search = input.value.trim().toLowerCase();
      let anyMatch = false;
      dropdown.querySelectorAll(".multiselect-option").forEach(option => {
        const match = (option.dataset.value ?? "").toLowerCase().includes(search);
        option.classList.toggle("noShow", !match);
        if (match) anyMatch = true;
      });
      dropdown.classList.toggle("noShow", !anyMatch);
      dropdown.classList.toggle("showFlex", anyMatch);
    };

    if (input) {
      input.addEventListener("focus", filterDropdown);
      input.addEventListener("input", filterDropdown);
      input.addEventListener("blur", hideDropdown);

      input.addEventListener("keydown", async ev => {
        const dropdownOpen = dropdown && !dropdown.classList.contains("noShow");

        if (ev.key === "Escape" && dropdownOpen) {
          ev.preventDefault();
          ev.stopPropagation();
          hideDropdown();
          return;
        }

        if ((ev.key === "ArrowDown" || ev.key === "ArrowUp") && dropdown) {
          if (!dropdownOpen) {
            filterDropdown();
            return;
          }
          ev.preventDefault();
          const options = visibleOptions();
          if (!options.length) return;
          const current = options.findIndex(option => option.classList.contains("multiselect-option-active"));
          const next = ev.key === "ArrowDown"
            ? (current + 1) % options.length
            : (current <= 0 ? options.length - 1 : current - 1);
          clearHighlight();
          options[next].classList.add("multiselect-option-active");
          options[next].scrollIntoView({ block: "nearest" });
          return;
        }

        if (ev.key !== "Enter") return;
        ev.preventDefault();

        // Enter picks the arrow-key-highlighted suggestion if there is one,
        // otherwise it adds the literal typed text (free-text entries stay allowed)
        const highlighted = dropdownOpen ? dropdown.querySelector(".multiselect-option-active:not(.noShow)") : null;
        if (highlighted) {
          hideDropdown();
          await addValue(highlighted.dataset.value);
          return;
        }
        await addValue(input.value);
      });
    }

    if (dropdown && input) {
      // mousedown would normally move focus off the input, firing its blur handler and
      // closing the dropdown before the click can land - swallow it (scrollbar drags included)
      dropdown.addEventListener("mousedown", ev => ev.preventDefault());

      dropdown.querySelectorAll(".multiselect-option").forEach(option => {
        option.addEventListener("click", async ev => {
          ev.preventDefault();
          hideDropdown();
          await addValue(ev.currentTarget.dataset.value);
        });
      });
    }

    widget.querySelectorAll(".multiselect-pill-remove").forEach(element => {
      element.addEventListener("click", async ev => {
        const index = Number(ev.currentTarget.dataset.index);
        const values = foundry.utils.duplicate(foundry.utils.getProperty(actor, path) ?? []);
        if (Number.isNaN(index) || !values[index]) return;

        values.splice(index, 1);
        await actor.update({ [path]: values });
      });
    });
  });
}

/**
 * Sister to multiSelectPills() for a purely client-side filter that is never persisted to a
 * document - reuses the same ".multiselect-widget" markup/CSS (see
 * templates/actor/partials/multiselect-pills.html), but add/remove mutate an array on the sheet
 * instance itself and re-render, instead of writing to actor data. No free-text entry - only
 * clicking a suggested option adds it, matched via its data-key (the raw filter value, distinct
 * from the localized data-value used for display).
 * @param {Object} html - The HTML object to which the event listeners are added
 * @param {Object} sheet - The ApplicationV2 sheet instance whose `filterProperty` array holds the active filter
 * @param {String} filterProperty - The property name on `sheet` holding the filter array
 */
export function itemTypeFilterPills(html, sheet, filterProperty) {
  html.querySelectorAll(`.multiselect-widget[data-path="${filterProperty}"]`).forEach(widget => {
    const input = widget.querySelector(".multiselect-input");
    const dropdown = widget.querySelector(".multiselect-dropdown");

    const hideDropdown = () => dropdown?.classList.add("noShow");

    const filterDropdown = () => {
      if (!dropdown) return;
      const search = input.value.trim().toLowerCase();
      let anyMatch = false;
      dropdown.querySelectorAll(".multiselect-option").forEach(option => {
        const match = (option.textContent ?? "").trim().toLowerCase().includes(search);
        option.classList.toggle("noShow", !match);
        if (match) anyMatch = true;
      });
      dropdown.classList.toggle("noShow", !anyMatch);
    };

    if (input) {
      input.addEventListener("focus", filterDropdown);
      input.addEventListener("input", filterDropdown);
      input.addEventListener("blur", hideDropdown);
      input.addEventListener("keydown", ev => {
        if (ev.key === "Escape") {
          ev.preventDefault();
          hideDropdown();
        }
      });
    }

    if (dropdown) {
      // mousedown would normally move focus off the input, firing its blur handler and closing
      // the dropdown before the click can land - swallow it, same as multiSelectPills().
      dropdown.addEventListener("mousedown", ev => ev.preventDefault());

      dropdown.querySelectorAll(".multiselect-option").forEach(option => {
        option.addEventListener("click", ev => {
          ev.preventDefault();
          hideDropdown();
          const key = ev.currentTarget.dataset.key;
          if (!key || sheet[filterProperty].includes(key)) return;
          sheet[filterProperty].push(key);
          sheet.render();
        });
      });
    }

    widget.querySelectorAll(".multiselect-pill-remove").forEach(element => {
      element.addEventListener("click", ev => {
        const index = Number(ev.currentTarget.dataset.index);
        if (Number.isNaN(index) || !sheet[filterProperty][index]) return;
        sheet[filterProperty].splice(index, 1);
        sheet.render();
      });
    });
  });
}

