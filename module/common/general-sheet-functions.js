/**
 * Foundry VTTs active effect creation & deletion functions
 * @param {Object} html - The HTML object to which the event listeners are added
 * @param {*} callerobj 
 */
export function registerEffectHandlers(html, callerobj) {
  html.querySelectorAll(".effect-create").forEach(button => {
    button.addEventListener("click", async () => {
      await callerobj.createEmbeddedDocuments("ActiveEffect", [{
        name: callerobj.name,
        label: callerobj.name,
        icon: "/icons/svg/mystery-man.svg"
      }]);
    });
  });

  html.querySelectorAll(".effect-edit").forEach(button => {
    button.addEventListener("click", event => {
      const li = event.currentTarget.closest(".effect");
      if (!li) return;

      const effectId = li.dataset.itemId;
      if (!effectId) return;

      const effect = callerobj.getEmbeddedDocument("ActiveEffect", effectId);
      effect?.sheet?.render(true);
    });
  });

  html.querySelectorAll(".effect-delete").forEach(button => {
    button.addEventListener("click", async event => {
      const askForOptions = event.shiftKey;
      const li = event.currentTarget.closest(".effect");
      if (!li) return;

      const effectId = li.dataset.itemId;
      if (!effectId) return;

      if (!askForOptions) {
        const itemName = li.dataset.itemName ?? null;
        const popUpTitle = game.i18n.localize("ep2e.actorSheet.dialogHeadline.confirmationNeeded");
        const popUpHeadline = `${game.i18n.localize("ep2e.actorSheet.button.delete")} ${itemName ?? ""}`;
        const popUpCopy = "ep2e.actorSheet.popUp.deleteCopyGeneral";
        const popUpInfo = "ep2e.actorSheet.popUp.deleteAdditionalInfo";

        const popUp = await confirmation(popUpTitle, popUpHeadline, popUpCopy, popUpInfo);

        if (popUp.confirm === true) {
          await callerobj.deleteEmbeddedDocuments("ActiveEffect", [effectId]);
        }
      } else {
        await callerobj.deleteEmbeddedDocuments("ActiveEffect", [effectId]);
      }
    });
  });
}

/**
 * Function to create temporary effects. These effects are used to be automatically 
 * deleted under certain circumstances. Therefore they're marked accordingly
 * @param {Object} actor - The actor object effects are added to
 * @param {Number} numberOfRuns - Serves as a multiplier to the effect value (tempEffVal)
 * @param {String} tempEffLabel - The label of the temporary effect
 * @param {String} tempEffIcon - The icon of the temporary effect
 * @param {String} tempEffTar - The target value of the temporary effect
 * @param {String} tempEffMode - The mode of the temporary effect
 * @param {Array} changes - An array with all changes in objects => {key, mode, value}
 * @param {String} effKey - a flag to localize temporary effects easily later on 
 * @param {Number} [hours] - How long the effect lasts on the world clock, left out for one that only ends on an event
 * @param {*} tempEffVal - The value of the temporary effect
 * @returns 
 */
export async function tempEffectCreation(actor, tempEffLabel, tempEffIcon, effChanges, effKey, hours){
    const effectData = {
      name: tempEffLabel,
      label: tempEffLabel,
      icon: tempEffIcon,
      changes: effChanges,
      // A duration would otherwise put an icon on the token, which this system does not want.
      showIcon: CONST.ACTIVE_EFFECT_SHOW_ICON.NEVER,
      flags: {
        eclipsephase: {
          effectKey: effKey
        }
      }
    };

    // expiry null so the hours run down on the world clock rather than on a combat turn.
    if (hours) effectData.duration = { value: hours, units: "hours", expiry: null };

    return actor.createEmbeddedDocuments('ActiveEffect', [effectData]);
}

/**
 * Filters actor for a specific flagged active effect
 * @param {Object} actor - The actor object
 * @param {String} scope - Usually "eclipsephase" if generated by the system
 * @param {String} key - Usually "effectKey" if generated by the system
 * @param {Array} values - An array with your flags to be deleted (e.g. [str1, str2, ...]). str1/str2 are strings in nature
 */
export async function tempEffectDeletion(actor, scope, key, values) {
  const effectsToDelete = actor.effects
    .filter(effect => values.includes(effect.getFlag(scope, key)))
    .map(effect => effect.id);

  if (effectsToDelete.length > 0) {
    await actor.deleteEmbeddedDocuments("ActiveEffect", effectsToDelete);
  }
}

/**
 * Deletes the system's own temporary effects once their time has run out. Foundry only marks an
 * expired effect, so without this a spent Ignore Wound would linger on the sheet after it stopped
 * applying. The other half of the RAW rule - ending at the next recharge - is handled where
 * recharges are taken.
 * @param {Actor} actor - The actor whose effects were refreshed
 * @param {ActiveEffect[]} effects - The effects whose remaining duration changed
 * @returns {Promise<void>} Resolves once the spent effects are gone
 */
export function deleteRunOutTempEffects(actor, effects) {
  return deleteRunOutEffects(actor, effects, "effectKey");
}

/**
 * Deletes the effects carrying one of the system's flags whose duration has run out.
 * @param {Actor} actor - The actor the effects are on
 * @param {ActiveEffect[]} effects - The effects to look through
 * @param {String} flag - The flag that marks them, e.g. "dose"
 * @returns {Promise<void>} Resolves once they are gone
 */
export async function deleteRunOutEffects(actor, effects, flag) {
  const spent = effects.filter(effect => effect.getFlag?.("eclipsephase", flag) !== undefined && durationRunOut(effect));
  if (spent.length) await actor.deleteEmbeddedDocuments("ActiveEffect", spent.map(effect => effect.id));
}

/**
 * The data of an effect that runs on the world clock: started now, ending after its span - or
 * running until ended when it has none - and marked with the system's flags.
 * @param {Object} options - name, img, span ({value, units}), flags (under eclipsephase), and
 *   optionally changes, statuses, showIcon, description, origin
 * @returns {Object} The ActiveEffect data
 */
export function timedEffectData({ name, img, span, flags = {}, changes = [], statuses = [], showIcon = CONST.ACTIVE_EFFECT_SHOW_ICON.NEVER, description = "", origin = null }) {
  return {
    name,
    img,
    origin,
    description,
    disabled: false,
    transfer: false,
    changes,
    system: { changes },
    statuses,
    duration: isTimedSpan(span) ? { value: span.value, units: span.units, expiry: null } : { value: null, expiry: null },
    start: ActiveEffect.getEffectStart(),
    showIcon,
    flags: { eclipsephase: flags }
  };
}

